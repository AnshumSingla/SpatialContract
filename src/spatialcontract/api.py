"""Check an in-memory function against a spatial contract without restructuring it into a ``process`` script.

    @spatial_contract(world_frame="RAS", units="mm")
    def crop(img: nib.Nifti1Image) -> nib.Nifti1Image: ...

    check_function(crop).verdict           # "PASS" | "FAIL" | "ERROR" | "ABSTAIN"

Two call signatures are supported: ``signature="image"`` (nibabel image -> nibabel image) and ``signature="array"``
((array, affine) -> (array, affine)). The function is adapted to the oracle's ``process(in_path, out_path)`` by a generated
driver module that imports it by module + qualname, and the unmodified ``oracle.check`` runs that driver in its usual scrubbed
subprocess, so the measurement, tolerances and verdicts are exactly the oracle's. A function a subprocess cannot import
(defined in ``__main__``, a notebook, inside another function, a lambda) raises ``NotImportable``; ``isolate=False`` runs it in
this process instead, through the same oracle measurement code, without the crash and environment isolation.

``affine_convention`` defaults to ``voxel_center_to_world`` here because that is how nibabel defines an image affine (and the
only convention the oracle supports); ``world_frame`` and ``units`` have no defaults, and a contract missing them ABSTAINs.
"""
from __future__ import annotations

import importlib
import importlib.util
import os
import sys
import tempfile
from dataclasses import dataclass
from pathlib import Path

import numpy as np

from . import oracle
from .contract import SpatialContract

SIGNATURES = ("image", "array")
CONTRACT_FIELDS = ("world_frame", "units", "affine_convention", "array_orientation")
DEFAULT_CONVENTION = "voxel_center_to_world"
_DRIVER = '''"""Generated by spatialcontract.api: adapts {qualname} to the oracle's process(in_path, out_path)."""
import sys
sys.path[:0] = {paths!r}
from spatialcontract.api import _adapter, _load_target
process = _adapter(_load_target({target!r}), {signature!r})
'''


class NotImportable(ValueError):
    """The function cannot be imported by the oracle's subprocess."""


class SpatialContractViolation(AssertionError):
    """Raised by ``assert_spatial_contract``; the message carries the oracle's millimetre feedback."""

    def __init__(self, report: oracle.Report):
        self.report = report
        super().__init__(f"{summary(report)}\n{report.feedback()}")


@dataclass(frozen=True)
class Declaration:
    contract: SpatialContract
    signature: str = "image"


def declare(world_frame=None, units=None, affine_convention=None, array_orientation=None, signature="image") -> Declaration:
    """The contract and call signature a function declares. Shared by the decorator and the CLI's static reader."""
    if signature not in SIGNATURES:
        raise ValueError(f"signature {signature!r} not one of {SIGNATURES}")
    return Declaration(SpatialContract(world_frame, units, affine_convention or DEFAULT_CONVENTION, array_orientation), signature)


def spatial_contract(fn=None, *, world_frame=None, units=None, affine_convention=None, array_orientation=None,
                     signature="image"):
    """Declare a function's spatial contract. The function is returned unchanged (no wrapper, no runtime cost); the
    declaration is stored on ``fn.__spatial_contract__`` and read by ``check_function``, the pytest fixture and the CLI."""
    decl = declare(world_frame, units, affine_convention, array_orientation, signature)

    def mark(f):
        f.__spatial_contract__ = decl
        return f
    return mark(fn) if fn is not None else mark


def check_function(fn, *, world_frame=None, units=None, affine_convention=None, array_orientation=None, contract=None,
                   signature=None, seeds=oracle.DEFAULT_SEEDS, tol_mm: float = oracle.DEFAULT_TOL_MM, isolate: bool = True,
                   python: str | None = None, pythonpath: list | None = None) -> oracle.Report:
    """Run the oracle on an in-memory function. The contract is the decorator's declaration, overridden by ``contract``
    (dict or SpatialContract) and then by any explicit field argument; a contract that is missing or unusable ABSTAINs
    without running the function. ``pythonpath`` adds import roots for the subprocess (it already sees this sys.path)."""
    decl = getattr(fn, "__spatial_contract__", None)
    fields = decl.contract.to_dict() if decl else {}
    if contract is not None:
        fields |= {k: v for k, v in (contract.to_dict() if isinstance(contract, SpatialContract) else contract).items()
                   if k in CONTRACT_FIELDS}
    given = dict(world_frame=world_frame, units=units, affine_convention=affine_convention, array_orientation=array_orientation)
    fields |= {k: v for k, v in given.items() if v is not None}
    d = declare(**fields, signature=signature or (decl.signature if decl else "image"))
    if not isolate:
        return _check_in_process(fn, d, seeds, tol_mm)
    return _check_target(_import_target(fn), d, seeds, tol_mm, python, pythonpath)


def assert_spatial_contract(fn, **kwargs) -> oracle.Report:
    """``check_function`` that raises ``SpatialContractViolation`` (an AssertionError) unless the verdict is PASS."""
    rep = check_function(fn, **kwargs)
    if not rep.passed:
        raise SpatialContractViolation(rep)
    return rep


def summary(rep: oracle.Report) -> str:
    """One line: the verdict and the single most telling measurement."""
    if rep.verdict == "ABSTAIN":
        return "ABSTAIN  spatial contract unusable: " + "; ".join(rep.reasons)
    if rep.verdict == "ERROR":
        p = next((p for p in rep.phantoms if p.status == "ERROR"), None)
        return f"ERROR  phantom seed {p.seed}: {p.detail}" if p else "ERROR  " + "; ".join(rep.reasons)
    if rep.worst() is None:
        return f"{rep.verdict}  no phantom was checked"
    err, seed, label = rep.worst()
    if err == float("inf"):
        return f"{rep.verdict}  landmark {label} lost from the output (phantom seed {seed})"
    line = f"{rep.verdict}  worst landmark {err:.{1 if err >= 10 else 2}f} mm off (phantom seed {seed}, label {label})"
    bad_orient = [p for p in rep.phantoms if p.orientation_ok is False]
    if bad_orient and all(lm.ok for p in rep.phantoms for lm in p.landmarks):
        p = bad_orient[0]
        line = (f"FAIL  output axes {p.out_axcodes}, contract requires array_orientation "
                f"{rep.contract['array_orientation']} (phantom seed {p.seed})")
    return line


# --- adapting a function to process(in_path, out_path) ------------------------------------------------------------------
def _adapter(fn, signature: str):
    """``process(in_path, out_path)`` around ``fn``; used by the generated driver and by the in-process mode alike."""
    import nibabel as nib

    def process(in_path, out_path):
        img = nib.load(str(in_path))
        if signature == "image":
            out = fn(img)
            if not isinstance(out, nib.spatialimages.SpatialImage):
                raise TypeError(f"expected the function to return a nibabel image, got {type(out).__name__}")
        else:
            res = fn(np.asanyarray(img.dataobj), np.array(img.affine, dtype=float))
            if not (isinstance(res, tuple) and len(res) == 2):
                raise TypeError(f"expected the function to return (array, affine), got {type(res).__name__}")
            data, aff = np.asarray(res[0]), np.asarray(res[1], dtype=float)
            if data.dtype == bool:
                data = data.astype(np.uint8)
            out = nib.Nifti1Image(data, aff, dtype=data.dtype)
        nib.save(out, str(out_path))
    return process


def _import_target(fn) -> dict:
    """Where the subprocess finds ``fn``; raises NotImportable if it cannot."""
    mod_name, qual = getattr(fn, "__module__", None), getattr(fn, "__qualname__", None)
    name = qual or type(fn).__name__
    why = None
    if not qual:
        why = "it has no __qualname__ (an instance or partial?)"
    elif "<lambda>" in qual or "<locals>" in qual:
        why = "it is a lambda or is defined inside another function"
    elif mod_name in (None, "__main__") or getattr(sys.modules.get(mod_name), "__file__", None) is None:
        why = f"it is defined in {mod_name or 'an unknown module'} (a script run directly, a notebook or the REPL)"
    else:
        obj = sys.modules[mod_name]
        for part in qual.split("."):
            obj = getattr(obj, part, None)
        if obj is not fn:
            why = f"{mod_name}.{qual} does not resolve to this function object (shadowed or wrapped?)"
    if why:
        raise NotImportable(f"cannot check {name} in an isolated subprocess: {why}. Move it to a module-level def in an "
                            f"importable module, or pass isolate=False to run it in this process (no crash/env isolation).")
    return {"module": mod_name, "qualname": qual}


def _load_target(target: dict):
    if "file" in target:
        spec = importlib.util.spec_from_file_location(target["module"], target["file"])
        mod = importlib.util.module_from_spec(spec)
        sys.modules[target["module"]] = mod
        spec.loader.exec_module(mod)
    else:
        mod = importlib.import_module(target["module"])
    obj = mod
    for part in target["qualname"].split("."):
        obj = getattr(obj, part)
    return obj


def _check_target(target: dict, d: Declaration, seeds, tol_mm, python=None, pythonpath=None) -> oracle.Report:
    """Write the driver for ``target`` and run the unmodified oracle on it (scrubbed env, subprocess)."""
    if d.contract.problems():
        return oracle.check(Path(__file__), d.contract, seeds=seeds, tol_mm=tol_mm)   # ABSTAIN; nothing is run
    roots = [str(Path(target["file"]).resolve().parent)] if "file" in target else []
    paths = roots + [str(p) for p in pythonpath or []] + [os.path.abspath(p) if p else os.getcwd() for p in sys.path]
    with tempfile.TemporaryDirectory(prefix="sc_driver_") as tmp:
        driver = Path(tmp) / "sc_driver.py"
        driver.write_text(_DRIVER.format(qualname=target["qualname"], paths=paths, target=target, signature=d.signature),
                          encoding="utf-8")
        return oracle.check(driver, d.contract, seeds=seeds, tol_mm=tol_mm, python=python)


def _check_in_process(fn, d: Declaration, seeds, tol_mm) -> oracle.Report:
    # same oracle (measurement, tolerances, retry, verdict); only the runner is replaced, so the function runs in this process
    process = _adapter(fn, d.signature)

    def run_here(code_path, in_path, out_path, cwd, python=None, pythonpath=None):
        try:
            process(in_path, out_path)
        except Exception as e:
            return False, f"raised {type(e).__name__}: {str(e)[:200]}"
        return True, ""

    return oracle.check(Path(__file__), d.contract, seeds=seeds, tol_mm=tol_mm, run=run_here)
